/**
 * The one transformation that turns the monorepo's Template (`apps/template-default`) into a
 * standalone project: `copyTemplateSource`, then `makeStandalone`. The script that refreshes
 * `template-default` on Cloudflare Artifacts, which new projects fork, applies both.
 *
 * Node runs the scripts straight from this file, so it may only import `node:` modules and other
 * such files, with their `.ts` extension.
 */
import fs from "node:fs";
import path from "node:path";

import { createAgentSkillLinks } from "./agent-skills.ts";
import { type PackageManager, packageManagerVersions } from "./utils.ts";

/** Autogenerated, locally installed or local-only files, relative to the Template's root. */
export const EXCLUDED_TEMPLATE_PATHS: ReadonlySet<string> = new Set([
  "node_modules",
  "dist",
  ".tanstack",
  ".wrangler",
  ".vite-hooks",
  ".agents",
  ".claude",
  ".env",
  ".env.local",
  ".gitignore",
  "src/routeTree.gen.ts",
  "src/routes/_camox.tsx",
  "src/routes/_camox",
]);

/**
 * Reads the default `catalog:` map from a `pnpm-workspace.yaml`. Only flat `name: range` entries
 * are supported, which is all the workspace uses.
 */
export function readCatalog(workspaceYaml: string): Record<string, string> {
  const lines = workspaceYaml.split("\n");
  const start = lines.indexOf("catalog:");
  if (start === -1) return {};
  const catalog: Record<string, string> = {};
  for (const line of lines.slice(start + 1)) {
    const match = /^ {2}("?)([^"]+)\1:\s*(.+)$/.exec(line);
    if (!match) break;
    catalog[match[2]] = match[3].trim();
  }
  return catalog;
}

/** Reads the default `catalog:` map of the monorepo at `repoRoot`. */
export function readWorkspaceCatalog(repoRoot: string) {
  return readCatalog(fs.readFileSync(path.join(repoRoot, "pnpm-workspace.yaml"), "utf-8"));
}

/** Rewrites `dir`'s `package.json` after `mutate` changes it in place. */
function updatePackageJson(dir: string, mutate: (pkg: Record<string, any>) => void) {
  const pkgPath = path.join(dir, "package.json");
  const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf-8"));
  mutate(pkg);
  fs.writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
}

/**
 * Copies the Template without its excluded files, replacing `catalog:` ranges with the
 * workspace catalog's, since a project lives outside the workspace.
 */
export function copyTemplateSource(src: string, dest: string, catalog: Record<string, string>) {
  fs.rmSync(dest, { recursive: true, force: true });
  fs.cpSync(src, dest, {
    recursive: true,
    filter: (source) => {
      const rel = path.relative(src, source);
      return !rel || !EXCLUDED_TEMPLATE_PATHS.has(rel.split(path.sep).join("/"));
    },
  });

  updatePackageJson(dest, (pkg) => {
    for (const field of ["dependencies", "devDependencies", "peerDependencies"]) {
      for (const [name, range] of Object.entries<string>(pkg[field] ?? {})) {
        if (range !== "catalog:") continue;
        if (!catalog[name]) throw new Error(`[template] No catalog entry for "${name}".`);
        pkg[field][name] = catalog[name];
      }
    }
  });
}

const DEV_ONLY_BLOCK =
  /^[ \t]*\/\/[ \t]*camox-cli:dev-only-start[ \t]*\r?\n[\s\S]*?^[ \t]*\/\/[ \t]*camox-cli:dev-only-end[ \t]*\r?\n/gm;

/**
 * The dependency builds a project allows, from the monorepo's `allowBuilds`. Camox's own packages
 * skip pnpm's minimum release age, so a project installs a Camox release as soon as it's published.
 */
const PNPM_WORKSPACE = `allowBuilds:
  core-js: true
  esbuild: true
  msw: true
  protobufjs: true
  sharp: true
  workerd: true
minimumReleaseAgeExclude:
  - camox
  - "@camox/*"
`;

// npm strips .gitignore files when publishing, so the CLI can't ship the Template's.
const GITIGNORE = `node_modules
.DS_Store
dist
dist-ssr
*.local
count.txt
.env
.tanstack
.wrangler

# Auto generated by Camox
src/routes/(camox)/

# Auto generated by Tanstack Router
src/routeTree.gen.ts
`;

/**
 * Turns a copy made by `copyTemplateSource` into a project that installs on its own: it depends
 * on the published `camox` instead of the workspace's, and loses the lines that only make sense
 * in the monorepo (marked `camox-cli:dev-only`). Project-specific values, such as the Project ID and the
 * `{{projectName}}` placeholders, are left for whoever creates the project.
 */
export function makeStandalone(
  dir: string,
  options: { camoxVersion: string; packageManager: PackageManager },
) {
  const viteConfigPath = path.join(dir, "vite.config.ts");
  fs.writeFileSync(
    viteConfigPath,
    fs.readFileSync(viteConfigPath, "utf-8").replace(DEV_ONLY_BLOCK, ""),
  );

  updatePackageJson(dir, (pkg) => {
    delete pkg.version;
    pkg.dependencies.camox = `^${options.camoxVersion}`;
    pkg.packageManager = packageManagerVersions[options.packageManager];
  });

  if (options.packageManager === "pnpm") {
    fs.writeFileSync(path.join(dir, "pnpm-workspace.yaml"), PNPM_WORKSPACE);
  }
  fs.writeFileSync(path.join(dir, ".gitignore"), GITIGNORE);
  createAgentSkillLinks(dir);
}

/** Replaces the Template's placeholder Project ID, marked by a comment this drops. */
export function replaceProjectId(source: string, projectId: string) {
  return source.replace(
    /"[^"]*"(,?)[ \t]*\/\/[ \t]*camox-cli:replace-project-id.*$/gm,
    `"${projectId}"$1`,
  );
}

/**
 * Names a standalone project's package after its slug, and points it, and the Worker it deploys
 * as, at its Project ID, which the dispatch Worker calls.
 */
export function personalize(dir: string, project: { slug: string; projectId: string }) {
  updatePackageJson(dir, (pkg) => {
    pkg.name = project.slug;
  });
  for (const file of ["vite.config.ts", "wrangler.jsonc"]) {
    const filePath = path.join(dir, file);
    fs.writeFileSync(
      filePath,
      replaceProjectId(fs.readFileSync(filePath, "utf-8"), project.projectId),
    );
  }
}
