import { Alert, AlertDescription, AlertTitle } from "@camox/ui/alert";
import { useSelector } from "@xstate/store-react";
import { useContext } from "react";

import type { PageRecordId } from "../pageRecord";
import { PreviewEditingOwnerContext } from "../previewSelection";
import { previewStore, selectionForOwner } from "../previewStore";
import { DerivedLayoutSidebar, type DerivedLayoutStructure } from "./DerivedLayoutSidebar";
import { DerivedPageInfoSidebar } from "./DerivedPageInfoSidebar";
import { PageEditorSidebar } from "./PageEditorSidebar";
import { PageInfoSidebar } from "./PageInfoSidebar";
import { PageTree } from "./PageTree";

/**
 * A page's sidebar content: its editor while something on it is selected,
 * otherwise its blocks, then what's about the page.
 */
const PageSidebar = ({
  pageId,
  derivedLayout,
  pageRecord,
}: {
  pageId?: string;
  derivedLayout?: DerivedLayoutStructure;
  /** The record of a record page. */
  pageRecord?: PageRecordId;
}) => {
  const owner = useContext(PreviewEditingOwnerContext);
  const selection = useSelector(previewStore, (state) => selectionForOwner(state.context, owner));
  // A block, or a record page's record (which no block places), opens the editor.
  if (selection != null) return <PageEditorSidebar />;

  if (pageId != null) {
    return (
      <div className="flex min-h-0 flex-1 flex-col overflow-auto">
        <section aria-label="Page blocks" className="flex flex-col gap-2 p-2">
          <PageTree />
        </section>
        <PageInfoSidebar pageId={pageId} scrollable={false} />
      </div>
    );
  }

  if (derivedLayout) {
    return (
      <div className="flex min-h-0 flex-1 flex-col overflow-auto">
        <DerivedLayoutSidebar layout={derivedLayout} pageRecord={pageRecord} />
        <DerivedPageInfoSidebar layoutId={derivedLayout.layoutId} />
      </div>
    );
  }

  return (
    <div className="p-2">
      <Alert>
        <AlertTitle>No page blocks</AlertTitle>
        <AlertDescription>
          This page’s content is generated by its layout, rather than assembled from page blocks.
        </AlertDescription>
      </Alert>
    </div>
  );
};

export { PageSidebar };
