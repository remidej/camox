import { uuidv7Schema } from "@camox/api-contract/ids";
import { z } from "zod";

import {
  updateFileMetadataInput,
  getProjectFile,
  listFiles,
  updateFile,
} from "../../../../apps/api/src/domains/files/service";
import { runService } from "../../../../apps/api/src/lib/run-service";
import type { ToolProvider } from "../types";

const target = z.object({ id: uuidv7Schema });
const updateInput = target.and(updateFileMetadataInput);

export const filesProvider: ToolProvider = (ctx) => [
  {
    name: "listFiles",
    description: "List files in the current project, as the draft sees them.",
    inputSchema: z.object({}),
    meta: { kind: "read", surfaces: ["cli", "studio-agent"] },
    handler: async () => runService(listFiles(ctx, { projectId: ctx.projectId })),
  },
  {
    name: "getFile",
    description: "Get an uploaded file, including its ID, URL, alt text and AI metadata setting.",
    inputSchema: target,
    meta: { kind: "read", surfaces: ["cli", "studio-agent"] },
    handler: async (input) =>
      runService(getProjectFile(ctx, { ...target.parse(input), projectId: ctx.projectId })),
  },
  {
    name: "updateFile",
    description:
      "Update a file's alt text, filename or automatic metadata. Alt text and filename are one group, generated by AI or written by hand: writing either makes both manual, keeping the generated value of the field not written; an empty string explicitly clears alt text. `aiMetadata: true` makes them generated again and schedules generation for raster images. Renaming preserves the file ID and URL.",
    inputSchema: updateInput,
    meta: { kind: "write", surfaces: ["cli", "studio-agent"] },
    handler: async (input) =>
      runService(updateFile(ctx, { ...updateInput.parse(input), projectId: ctx.projectId })),
  },
];
